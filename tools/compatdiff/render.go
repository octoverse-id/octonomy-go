package main

import (
	"fmt"
	"strings"
)

// compatReport is what COMPAT.md is written from: the pins, how much each baseline
// exports, and the carve-out file's sections -- whose feature lines are, once
// both checks pass, exactly the differences between the lines.
type compatReport struct {
	mainPin      string
	mainFeatures int
	releases     []releaseReport
	sections     []*section
}

type releaseReport struct {
	tag      string
	commit   string
	features int
}

const repoURL = "https://github.com/octoverse-id/octonomy-go"

// renderCompat writes COMPAT.md. Everything in it comes from the report; the
// fixed prose says only what the two checks compare, which is a fact about
// this tool, kept next to the code it describes.
func renderCompat(r compatReport) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("<!-- Generated by `make compat-md` (tools/compatdiff) from tools/compatdiff/carveouts.txt.\n")
	w("     Do not edit it here: `make compat-diff` fails when this file differs from what it would write. -->\n\n")
	w("# How this line differs from `/v2`\n\n")
	w("This branch is the Go 1.13 line: module `github.com/octoverse-id/octonomy-go`, versions `v1.x`.\n")
	w("`main` is the modern line, module `github.com/octoverse-id/octonomy-go/v2`, where capabilities\n")
	w("originate; this line ports them ([epic #88](%s/issues/88)).\n\n", repoURL)
	w("**This file is every difference between the two lines' exported APIs, and the reason for each.**\n")
	w("`tools/compatdiff` writes it from two checks, and `make compat-diff` fails when either finds\n")
	w("something this file does not account for:\n\n")
	w("1. **Parity with `main`**, at [`%s`](%s/tree/%s), the commit `tools/compatdiff/baselines.pin`\n", short(r.mainPin), repoURL, r.mainPin)
	w("   names. Every importable package on each side is compared declaration by declaration, by type\n")
	w("   identity rather than spelling: each package's name, constants with their types and values,\n")
	w("   variables, function and method signatures (the method sets of T and of *T), each type's kind\n")
	w("   and comparability, struct fields with their types and struct tags, each interface's whole\n")
	w("   method set, and which of a package's types satisfy its interfaces (%d features on `main` at\n", r.mainFeatures)
	w("   that commit). A difference not listed below fails the check, and so does a listed one that no\n")
	w("   longer exists.\n")
	w("2. **Compatibility with this line's published releases.** Every feature each one exported is\n")
	w("   still here, unchanged, and so is the order of each struct's exported fields, so code that\n")
	w("   compiled against it compiles against this line -- except\n")
	w("   an unkeyed struct literal, which any minor release may break ([`docs/versioning.md`](docs/versioning.md),\n")
	w("   the MINOR rule). This check has no exceptions:\n\n")
	for _, rel := range r.releases {
		w("   - [`%s`](%s/tree/%s) (`%s`): %d features.\n", rel.tag, repoURL, rel.tag, short(rel.commit), rel.features)
	}
	w("\nNot compared: each line's module path and the value of `Version`, which name the line rather\n")
	w("than describe it; parameter and type-parameter names (a type parameter prints by position,\n")
	w("`$0`); unexported declarations; and behaviour that changes no declaration. A\n")
	w("difference of that last kind appears below as prose with no features under it, and no check\n")
	w("holds it true -- it is as current as the pull request that last edited it.\n")

	groups := []struct {
		kind  sectionKind
		title string
		none  string
	}{
		{kindCarveout, "Deliberate differences", "None."},
		{kindDialect, "The irreducible type-name delta", "None."},
		{kindGap, "Open gaps", "None. Every difference above is deliberate or irreducible."},
	}
	for _, g := range groups {
		w("\n## %s\n", g.title)
		n := 0
		for _, s := range r.sections {
			if s.kind != g.kind {
				continue
			}
			n++
			title := s.title
			if s.kind == kindCarveout {
				title = fmt.Sprintf("%d. %s", n, s.title)
			}
			if s.kind == kindGap {
				title = fmt.Sprintf("%s ([%s](%s/issues/%s))", s.title, s.issue, repoURL, strings.TrimPrefix(s.issue, "#"))
			}
			w("\n### %s\n\n", title)
			w("%s\n", paragraphs(s.text))
			writeSide(&b, s, "main", "Only on `main`:")
			writeSide(&b, s, "compat", "Only on this line:")
			if len(s.lines) == 0 {
				w("\nNo declaration differs.\n")
			}
		}
		if n == 0 {
			w("\n%s\n", g.none)
		}
	}
	return b.String()
}

// paragraphs joins a section's text lines, an empty one ending a paragraph.
func paragraphs(text []string) string {
	var paras []string
	var cur []string
	for _, line := range append(text, "") {
		if strings.TrimSpace(line) == "" {
			if len(cur) > 0 {
				paras = append(paras, strings.Join(cur, "\n"))
				cur = nil
			}
			continue
		}
		cur = append(cur, line)
	}
	return strings.Join(paras, "\n\n")
}

func writeSide(b *strings.Builder, s *section, side, heading string) {
	var lines []string
	for _, e := range s.lines {
		if e.side == side {
			lines = append(lines, e.feature)
		}
	}
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(b, "\n%s\n\n```text\n%s\n```\n", heading, strings.Join(lines, "\n"))
}

func short(sha string) string {
	if len(sha) > 12 {
		return sha[:12]
	}
	return sha
}
